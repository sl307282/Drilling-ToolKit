with open('translations.js', 'r', encoding='utf-8') as f:
    content = f.read()

# Pattern to find each locale block: e.g., '  es: {\n' until next locale or end
for loc in locales:
    # Find the locale block
    # Note: en is the first one, 'uk' is the last
    loc_marker = f"  {loc}: {{"
    pos = content.find(loc_marker)
    if pos == -1:
        print(f"Error: could not find {loc_marker}")
        continue
    
    # We want to insert our new key-value pairs right after `loc_marker\n`
    insert_pos = pos + len(loc_marker) + 1
    
    lines_to_insert = []
    for key, trans_dict in new_translations.items():
        val = trans_dict[loc]
        # Escape quotes if necessary
        escaped_key = key.replace('"', '\\"')
        escaped_val = val.replace('"', '\\"')
        lines_to_insert.append(f'    "{escaped_key}": "{escaped_val}",\n')
    
    insertion_text = "".join(lines_to_insert)
    content = content[:insert_pos] + insertion_text + content[insert_pos:]

with open('translations.js', 'w', encoding='utf-8') as f:
    f.write(content)

