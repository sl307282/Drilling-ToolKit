def translate_zh(en_key, uk_val):
    if en_key in ZH_SPECIFIC:
        return ZH_SPECIFIC[en_key]
    
    # Check IADC patterns
    m = re.match(r'^#(\d+) - Cone #(\d+)$', en_key)
    if m:
        return f"#{m.group(1)} - 牙轮 #{m.group(2)}"
    
    m = re.match(r'^(\d+) - (\d+/\d+) Bearing Life Used$', en_key)
    if m:
        return f"{m.group(1)} - 消耗 {m.group(2)} 轴承寿命"
    
    m = re.match(r'^(\d+)\s*[–-]\s*(.*?) Wear$', en_key)
    if m:
        num = m.group(1)
        wtype = m.group(2)
        wmap = {
            "No": "无磨损",
            "Very Slight": "极轻微磨损",
            "Slight": "轻度磨损",
            "Light": "较轻磨损",
            "Moderate": "中度磨损",
            "Heavy": "重度磨损",
            "Severe": "严重磨损",
            "Very Severe": "极严重磨损",
            "Completely": "完全磨损"
        }
        return f"{num} – {wmap.get(wtype, wtype + '磨损')}"

    # General phrase substitution
    res = en_key
    for pattern, replacement in ZH_PHRASES:
        res = re.sub(pattern, replacement, res)
    return res
