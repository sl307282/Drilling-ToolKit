def translate_es(en_key, uk_val):
    if en_key in ES_SPECIFIC:
        return ES_SPECIFIC[en_key]
    
    # Check IADC patterns
    m = re.match(r'^#(\d+) - Cone #(\d+)$', en_key)
    if m:
        return f"#{m.group(1)} - Cono #{m.group(2)}"
    
    m = re.match(r'^(\d+) - (\d+/\d+) Bearing Life Used$', en_key)
    if m:
        return f"{m.group(1)} - {m.group(2)} de vida útil del cojinete usada"
    
    m = re.match(r'^(\d+)\s*[–-]\s*(.*?) Wear$', en_key)
    if m:
        num = m.group(1)
        wtype = m.group(2)
        wmap = {
            "No": "Sin desgaste",
            "Very Slight": "Desgaste muy leve",
            "Slight": "Desgaste leve",
            "Light": "Desgaste moderado-bajo",
            "Moderate": "Desgaste moderado",
            "Heavy": "Desgaste severo",
            "Severe": "Desgaste muy severo",
            "Very Severe": "Desgaste extremadamente severo",
            "Completely": "Completamente desgastado"
        }
        return f"{num} – {wmap.get(wtype, 'Desgaste ' + wtype.lower())}"

    # General phrase substitution
    res = en_key
    for pattern, replacement in ES_PHRASES:
        res = re.sub(pattern, replacement, res)
    return res
